
class AirQuality {
  final String city;
  final int aqi;
  final double pm25;
  final double pm10;
  final double carbonMonoxide;
  final double nitrogenDioxide;
  final double ozone;

  AirQuality({
    required this.city,
    required this.aqi,
    required this.pm25,
    required this.pm10,
    required this.carbonMonoxide,
    required this.nitrogenDioxide,
    required this.ozone,
  });
}
